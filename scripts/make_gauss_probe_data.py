#!/usr/bin/env python3
"""Write pico/probe/gauss_probe_weights.inc: the integer kernels the gauss_probe firmware runs (scripts/gauss_weights.py).

    python3 scripts/make_gauss_probe_data.py            # (re)writes the file
    python3 scripts/make_gauss_probe_data.py --check    # exits 1 if the committed file differs from what this would write

The probe uses sigma = max(r / 3, 0.5) for each radius r (a Gaussian cut at 3 sigma). pico/tools/gauss_probe_check.py builds
the same kernels with gauss_weights.py to compute the checksums the chip should print.
"""
import os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import gauss_weights as gw

RADII = (1, 2, 3, 4, 5, 7, 8, 15)
PATH = os.path.join(ROOT, "pico", "probe", "gauss_probe_weights.inc")


def sigma(r):
    return max(r / 3.0, 0.5)


def text():
    lines = ["/* GENERATED by scripts/make_gauss_probe_data.py - do not edit. Integer Gaussian kernels (sum 2^14), w[0] = centre. */",
             "#define PROBE_NR %d" % len(RADII), "static const uint32_t probe_radii[PROBE_NR] = {%s};" % ", ".join(map(str, RADII)),
             "static const int32_t probe_w[PROBE_NR][16] = {"]
    for r in RADII:
        w = gw.gaussian(sigma(r), r)
        lines.append("    {%s},  /* r = %d, sigma = %.4f */" % (", ".join(map(str, w + [0] * (16 - len(w)))), r, sigma(r)))
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    t = text()
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(PATH) and open(PATH).read() == t else 1)
    open(PATH, "w").write(t)
    print("wrote", PATH)
