#!/usr/bin/env python3
"""Generate pico/probe/probe_series.inc: a small synthetic DICOM series for the on-device probe.

The series is built with the test suite's independent DICOM writer (tests/dicomgen.py). It is chosen to
exercise many paths at once: an oblique orientation, signed 12-bit samples stored in 16 bits with garbage in
the unused bits, a fractional rescale slope, an inversion-recovery sequence, a field strength written in
gauss (a GE habit), anisotropic pixels, implicit VR, and planted identifying values that must never come out.
It contains no real patient data. The output is committed so the firmware build does not need Python.

usage: python3 scripts/make_probe_data.py
"""
import importlib.util, os, random

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
spec = importlib.util.spec_from_file_location("dicomgen", os.path.join(ROOT, "tests", "dicomgen.py"))
gen = importlib.util.module_from_spec(spec)
spec.loader.exec_module(gen)

ROWS, COLS, N = 20, 24, 8
rng = random.Random(2026)
tech = b"".join([
    gen.enc(0x18, 0x80, b"DS", b"2400", False), gen.enc(0x18, 0x81, b"DS", b"3.1", False), gen.enc(0x18, 0x82, b"DS", b"900", False),
    gen.enc(0x18, 0x1314, b"DS", b"8", False), gen.enc(0x18, 0x87, b"DS", b"15000", False),
    gen.enc(0x18, 0x20, b"CS", b"IR\\GR", False), gen.enc(0x18, 0x21, b"CS", b"SP\\MP", False), gen.enc(0x18, 0x23, b"CS", b"3D", False),
    gen.enc(0x18, 0x10, b"LO", b"CONTRAST AGENT", False), gen.enc(0x8, 0x70, b"LO", b"GE MEDICAL SYSTEMS", False),
    gen.enc(0x8, 0x1090, b"LO", b"PROBE_SCANNER", False), gen.enc(0x18, 0x1020, b"LO", b"09\\LX\\MR Software release:1.0", False),
    gen.enc(0x18, 0x1030, b"LO", b"probe protocol (3D)", False),
])
files = gen.stack(N, "oblique 2", rows=ROWS, cols=COLS, ps=(0.9, 0.75), dz=1.5, ts=gen.IMPL, extra_before=tech,
                  alloc=16, stored=12, high=11, signed=True, slope=2.5, inter=-100, burned=b"NO", removed=b"YES",
                  vals=lambda k: [rng.randint(-2048, 2047) for _ in range(ROWS * COLS)])

out = ["/* GENERATED by scripts/make_probe_data.py - do not edit. A synthetic %d-slice DICOM series (no real data)." % N,
       " * Each file is stored back to back in probe_series[]; probe_lens[] gives their lengths. */",
       "#define PROBE_N %d" % N,
       "static const unsigned probe_lens[PROBE_N] = {%s};" % ", ".join(str(len(f)) for f in files),
       "static const unsigned char probe_series[] = {"]
blob = b"".join(files)
for i in range(0, len(blob), 16):
    out.append("    " + ", ".join("0x%02x" % b for b in blob[i:i + 16]) + ",")
out.append("};")
path = os.path.join(ROOT, "pico", "probe", "probe_series.inc")
open(path, "w").write("\n".join(out) + "\n")
print("wrote", path, "(%d files, %d bytes)" % (N, len(blob)))
